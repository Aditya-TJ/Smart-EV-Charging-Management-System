-- ----------------------------------------------------------------
-- View 1: v_available_points
-- Purpose: Supports Module M4 & Project PDF required output:
--          "Find available charging points at a selected station"
-- Concept: INNER JOIN between charging_point and charging_station,
--          filtering only 'available' points at 'active' stations.
-- ----------------------------------------------------------------
CREATE OR REPLACE VIEW v_available_points AS
SELECT 
    cp.point_id,
    cp.connector_type,
    cp.power_rating_kw,
    cp.status AS point_status,
    cs.station_id,
    cs.name AS station_name,
    cs.location AS station_location,
    cs.status AS station_status,
    cs.contact_number
FROM charging_point cp
INNER JOIN charging_station cs ON cp.station_id = cs.station_id
WHERE cp.status = 'available' 
  AND cs.status = 'active';

-- ----------------------------------------------------------------
-- View 2: v_charging_history
-- Purpose: Supports Module M7 & Project PDF required output:
--          "Find a user's charging history and total amount spent"
-- Concept: Multi-table JOIN (user, vehicle, station, point, plan)
--          with LEFT JOIN payment to dynamically derive payment_status:
--          'Paid' if payment exists, 'Pending' if completed with no payment,
--          'In Progress' if session is ongoing.
-- ----------------------------------------------------------------
CREATE OR REPLACE VIEW v_charging_history AS
SELECT 
    csess.session_id,
    csess.start_time,
    csess.end_time,
    TIMESTAMPDIFF(MINUTE, csess.start_time, csess.end_time) AS duration_minutes,
    csess.energy_consumed_kwh,
    csess.status AS session_status,
    u.user_id,
    u.name AS user_name,
    u.email AS user_email,
    u.phone AS user_phone,
    v.vehicle_id,
    v.vehicle_number,
    v.model AS vehicle_model,
    cs.station_id,
    cs.name AS station_name,
    cs.location AS station_location,
    cp.point_id,
    cp.connector_type,
    cp.power_rating_kw,
    tp.plan_id,
    tp.plan_name,
    tp.rate_per_kwh,
    p.payment_id,
    p.amount AS payment_amount,
    p.payment_date,
    p.payment_method,
    CASE 
        WHEN p.payment_id IS NOT NULL THEN 'Paid'
        WHEN csess.status = 'completed' THEN 'Pending'
        ELSE 'In Progress'
    END AS payment_status
FROM charging_session csess
INNER JOIN `user` u ON csess.user_id = u.user_id
INNER JOIN vehicle v ON csess.vehicle_id = v.vehicle_id
INNER JOIN charging_point cp ON csess.point_id = cp.point_id
INNER JOIN charging_station cs ON cp.station_id = cs.station_id
LEFT JOIN tariff_plan tp ON csess.plan_id = tp.plan_id
LEFT JOIN payment p ON csess.session_id = p.session_id;

-- ----------------------------------------------------------------
-- View 3: v_station_revenue
-- Purpose: Supports Module M8 & Project PDF required output:
--          "Total revenue generated by each charging station"
-- Concept: Double-counting protection: Aggregates sessions and payments
--          in a pre-aggregated derived table by station_id before
--          joining with charging_point. Preserves stations with zero
--          sessions and zero revenue via LEFT JOIN and COALESCE.
-- ----------------------------------------------------------------
CREATE OR REPLACE VIEW v_station_revenue AS
SELECT 
    cs.station_id,
    cs.name AS station_name,
    cs.location AS station_location,
    cs.status AS station_status,
    cs.total_slots,
    COUNT(DISTINCT cp.point_id) AS total_points,
    COALESCE(s.session_count, 0) AS session_count,
    COALESCE(s.total_energy_kwh, 0.00) AS total_energy_kwh,
    COALESCE(s.total_revenue, 0.00) AS total_revenue
FROM charging_station cs
LEFT JOIN charging_point cp ON cs.station_id = cp.station_id
LEFT JOIN (
    SELECT 
        cp2.station_id,
        COUNT(csess.session_id) AS session_count,
        COALESCE(SUM(csess.energy_consumed_kwh), 0.00) AS total_energy_kwh,
        COALESCE(SUM(p.amount), 0.00) AS total_revenue
    FROM charging_point cp2
    INNER JOIN charging_session csess ON cp2.point_id = csess.point_id
    LEFT JOIN payment p ON csess.session_id = p.session_id
    GROUP BY cp2.station_id
) s ON cs.station_id = s.station_id
GROUP BY cs.station_id, cs.name, cs.location, cs.status, cs.total_slots, s.session_count, s.total_energy_kwh, s.total_revenue;
